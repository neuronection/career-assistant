def normalize_language_code(value: str | None) -> str | None:
    """Lower-case ISO 639-1 code or a mapped name/639-2 code; else None."""
    if value is None:
        return None
    token = str(value).strip().lower()
    if not token:
        return None
    if _CODE_RE.fullmatch(token):
        return token if token in ISO_639_1 else None
    return LANGUAGE_ALIASES.get(token)


def is_language_code(value: str | None) -> bool:
    token = str(value or "").strip().lower()
    return bool(token and _CODE_RE.fullmatch(token) and token in ISO_639_1)
