"""The SDK doc-set truth gate (plan 128): everything ``docs/dev/sdk/``
prints is pinned to the law it describes — the runnable-examples rule
(family ``guidelines/extension-docs.md`` §3, "a code block that lies is
a bug") made mechanical.

Structure is walled elsewhere (``test_extension_docs_tree.py`` owns the
tree, ``test_connector_docs_api.py`` the per-extension docs surface).
This wall owns SEMANTIC drift: printed manifests must register through
the vendored validator, the error table must be charter-true, the RPC
table must name methods the protocol speaks, the knobs tables must match
``Settings``, and the template manifest must stay the pinned fixture.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from app.core.config import Settings
from app.extensions import contract
from app.extensions.polite_http import DEFAULT_RETRYABLE, ERROR_CODES
from app.extensions.runtime.sandbox import protocol as rpc_protocol

REPO_ROOT = Path(__file__).resolve().parents[2]
CONTRACTS_DIR = REPO_ROOT / "contracts"
SDK_DIR = REPO_ROOT / "docs" / "dev" / "sdk"
TEMPLATE_FIXTURE = REPO_ROOT / "backend" / "tests" / "fixtures" / "mcp_template_manifest.json"

MANIFEST_SCHEMA = json.loads(
    (CONTRACTS_DIR / "extension-manifest.schema.json").read_text(encoding="utf-8")
)
DOCS_TREE_SCHEMA = json.loads((CONTRACTS_DIR / "docs-tree.schema.json").read_text(encoding="utf-8"))
CHARTER = json.loads((CONTRACTS_DIR / "extension-charter.json").read_text(encoding="utf-8"))
CAREER_PROFILE = next(
    profile
    for profile in CHARTER["hostProfiles"]["profiles"]
    if profile["product"] == "career-assistant"
)

FENCE_RE = re.compile(r"^```([^\n]*)\n(.*?)^```[ \t]*$", re.MULTILINE | re.DOTALL)
ERROR_ROW_RE = re.compile(
    r"^\| `([a-z][a-z-]*)` \| [^|\n]+ \| `([a-z-]+)`[^|\n]*\|$",
    re.MULTILINE,
)
KNOB_RE = re.compile(r"\bCAREER_[A-Z0-9_]+\b")


def _fences() -> list[tuple[str, str, str]]:
    out: list[tuple[str, str, str]] = []
    for path in sorted(SDK_DIR.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        for match in FENCE_RE.finditer(text):
            out.append((path.name, match.group(1).strip(), match.group(2)))
    return out


def _json_blocks() -> list[tuple[str, str, Any]]:
    out: list[tuple[str, str, Any]] = []
    for name, info, body in _fences():
        if "json" not in info.split():
            continue
        try:
            out.append((name, info, json.loads(body)))
        except json.JSONDecodeError:
            continue
    return out


def _parses(body: str) -> bool:
    try:
        json.loads(body)
    except json.JSONDecodeError:
        return False
    return True


def _manifest_blocks() -> list[tuple[str, dict, bool]]:
    return [
        (name, doc, "bundled" in info.split())
        for name, info, doc in _json_blocks()
        if isinstance(doc, dict) and "apiVersion" in doc and "kind" in doc
    ]


def _docs_tree_blocks() -> list[tuple[str, dict]]:
    return [
        (name, doc)
        for name, _info, doc in _json_blocks()
        if isinstance(doc, dict)
        and "apiVersion" not in doc
        and "version" in doc
        and "categories" in doc
    ]


def _bundle_tree() -> dict:
    return {
        "version": 1,
        "categories": [
            {
                "category": "overview",
                "items": [
                    {
                        "id": "overview",
                        "title": "Overview",
                        "description": "Generated by the docs-truth gate.",
                        "file": "overview.md",
                    }
                ],
            }
        ],
    }


def _materialize(root: Path, manifest: dict) -> Path:
    bundle = root / "bundle"
    (bundle / "docs").mkdir(parents=True, exist_ok=True)
    entry = manifest.get("entry")
    if isinstance(entry, str):
        target = bundle / entry
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text("# entry stub\n", encoding="utf-8")
    if isinstance(manifest.get("docs"), str):
        (bundle / "docs" / "docs-tree.json").write_text(
            json.dumps(_bundle_tree()), encoding="utf-8"
        )
        (bundle / "docs" / "overview.md").write_text("# Overview\n", encoding="utf-8")
    return bundle


def _register(manifest: dict, *, bundled: bool, bundle: Path) -> list[str]:
    return contract.validate_registration(
        manifest,
        schema=MANIFEST_SCHEMA,
        bundled=bundled,
        profile=CAREER_PROFILE,
        docs_root=bundle,
        docs_schema=DOCS_TREE_SCHEMA,
        charter=CHARTER,
        byte_size=len(json.dumps(manifest)),
    )


# ------------------------------------------------------- printed manifests


def test_no_json_fence_fails_to_parse() -> None:
    broken = [
        (name, body.splitlines()[0] if body.splitlines() else "")
        for name, info, body in _fences()
        if "json" in info.split() and not _parses(body)
    ]
    assert not broken, (
        "json-tagged fences that are not valid JSON (they would silently vanish "
        "from every pin below): " + repr(broken)
    )


def test_the_set_prints_manifests_at_all() -> None:
    assert len(_manifest_blocks()) >= 3, "manifest parser found too few blocks — drifted?"


def test_every_printed_manifest_registers(tmp_path) -> None:
    failures: list[str] = []
    for index, (name, manifest, bundled) in enumerate(_manifest_blocks()):
        bundle = _materialize(tmp_path / str(index), manifest)
        problems = _register(manifest, bundled=bundled, bundle=bundle)
        if problems:
            failures.append(f"{name}: {manifest.get('id')!r} -> {problems}")
    assert not failures, "printed manifests that would not register:\n" + "\n".join(failures)


def test_the_template_manifest_is_the_pinned_fixture() -> None:
    fixture = json.loads(TEMPLATE_FIXTURE.read_text(encoding="utf-8"))
    printed = [
        manifest
        for _name, manifest, _bundled in _manifest_blocks()
        if manifest.get("id") == "example-posting-fetcher"
    ]
    assert len(printed) == 1
    assert printed[0] == fixture, (
        "authoring-and-configuration.md's template manifest drifted from "
        "tests/fixtures/mcp_template_manifest.json — the doc set claims verbatim"
    )


def test_the_arbeitnow_block_is_the_builtin_file() -> None:
    manifest_path = (
        REPO_ROOT / "backend" / "app" / "extensions" / "builtin" / "arbeitnow" / "manifest.json"
    )
    builtin = json.loads(manifest_path.read_text(encoding="utf-8"))
    printed = [
        manifest
        for _name, manifest, _bundled in _manifest_blocks()
        if manifest.get("id") == "career-arbeitnow"
    ]
    assert len(printed) == 1
    assert printed[0] == builtin, (
        "examples-and-use-cases.md's Arbeitnow manifest drifted from "
        "app/extensions/builtin/arbeitnow/manifest.json — the recipe claims verbatim"
    )


def test_every_printed_docs_tree_validates() -> None:
    failures: list[str] = []
    for name, tree in _docs_tree_blocks():
        structural = contract.validate(DOCS_TREE_SCHEMA, tree, DOCS_TREE_SCHEMA)
        semantic = contract.docs_tree_semantics(tree, exists=lambda _ref: True)
        if structural or semantic:
            failures.append(f"{name} -> {[structural, *semantic]}")
    assert not failures, "printed docs trees that would not validate:\n" + "\n".join(failures)


def test_the_gate_detects_a_lying_manifest(tmp_path) -> None:
    fixture = json.loads(TEMPLATE_FIXTURE.read_text(encoding="utf-8"))
    drifted = {key: value for key, value in fixture.items() if key not in ("entry", "mcp")}
    problems = _register(drifted, bundled=False, bundle=_materialize(tmp_path, drifted))
    assert any("entry" in problem for problem in problems), (
        "the registration seam no longer rejects the exact drift class that "
        "shipped (an imported connector printed without its entry)"
    )


# ------------------------------------------------------------ vocabularies


def test_the_error_table_is_charter_true() -> None:
    text = (SDK_DIR / "reference.md").read_text(encoding="utf-8")
    table = dict(ERROR_ROW_RE.findall(text))
    charter = {row["code"]: row["retryable"] for row in CHARTER["errors"]["codes"]}
    runtime = {code: DEFAULT_RETRYABLE[code] for code in ERROR_CODES}
    assert table == charter, "reference.md error table drifted from the vendored charter"
    assert table == runtime, "reference.md error table drifted from the polite runtime's defaults"


def test_the_rpc_table_names_methods_the_protocol_speaks() -> None:
    text = (SDK_DIR / "reference.md").read_text(encoding="utf-8")
    section = text.split("## The capability-RPC protocol", 1)[1].split("\n## ", 1)[0]
    documented: set[str] = set()
    for line in section.splitlines():
        if line.startswith("| `"):
            documented.update(re.findall(r"`([^`]+)`", line.split("|")[1]))
    spoken = (
        set(rpc_protocol.CAP_METHODS)
        | set(rpc_protocol.HOST_METHODS)
        | set(rpc_protocol.EVENT_METHODS)
    )
    assert documented == spoken


def test_the_knobs_tables_match_settings() -> None:
    text = (SDK_DIR / "reference.md").read_text(encoding="utf-8")
    documented = {knob for knob in KNOB_RE.findall(text) if not knob.endswith("_")}
    known = {"CAREER_" + name.upper() for name in Settings.model_fields}
    read_by_subsystem: set[str] = set()
    for path in (REPO_ROOT / "backend" / "app" / "extensions").rglob("*.py"):
        source = path.read_text(encoding="utf-8")
        read_by_subsystem.update(
            "CAREER_" + attr.upper()
            for attr in re.findall(r"\bsettings\.([a-z_][a-z0-9_]*)", source)
        )
    read_by_subsystem &= known
    assert not read_by_subsystem - documented, (
        "knobs the extensions subsystem reads but reference.md never documents"
    )
    assert not documented - known, "reference.md documents knobs Settings does not define"


def test_every_honored_capability_is_named() -> None:
    text = (SDK_DIR / "authoring-and-configuration.md").read_text(encoding="utf-8")
    missing = [cap for cap in CAREER_PROFILE["honors"] if f"`{cap}`" not in text]
    assert not missing, "capabilities this host honors but the authoring chapter never names"
